import java.util.*;
class Relational 
{
	public static void main(String[] args) 
	{
    Scanner sc=new Scanner(System.in);
     int x = sc.nextInt();
     int y = sc.nextInt();
		System.out.println(x==y);
		System.out.println(x>y);
		System.out.println(x<y);
		System.out.println(x>=40);
		System.out.println(y<=80);
		System.out.println(x!=y);
	}
}
